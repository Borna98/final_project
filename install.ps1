# 1. Navigate to the project directory
cd D:\PythonProjects\documentintelligence

# 2. Create a virtual environment (if not already created)
```bash
python -m venv .venv
```

# 3. Activate the virtual environment

```bash
.venv\Scripts\Activate.ps1
```

# 4. Install required dependencies

```bash
pip install -r requirements.txt
```

# 5. Run the main script

```bash
python src/main.py -w 
```

# 6. Deactivate the virtual environment after running the script

```bash
deactivate
```

# 7. Optional: If you want to run the script in a Jupyter Notebook, you can start Jupyter Notebook and open the `pipeline.ipynb` file.  

```bash 
jupyter notebook
``` 

# 8. Optional: If you want to run the script in VS Code, you can open the project folder in VS Code and run the `main.py` file directly from the editor.

